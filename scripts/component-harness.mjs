#!/usr/bin/env node
// Reproducible CSF stories from the read-only design inventory + MCP-derived specimen fixture.
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = (path) => JSON.parse(readFileSync(root + path, "utf8"));
const fixture = read("packages/editor-react/fixtures/components.json");
const inventory = read("docs/design/snapshots/inventory.json");
assert.equal(
  fixture.source_sha256,
  inventory.source_sha256,
  "Component harness design source is stale",
);
assert.deepEqual(
  fixture.boards.map((b) => b.id).sort(),
  inventory.frames
    .filter((f) => f.kind === "components" || f.kind === "library")
    .map((f) => f.frame_id)
    .sort(),
  "Every Components and Library board must be inventoried",
);
assert.equal(
  new Set(fixture.cases.map((c) => c.id)).size,
  fixture.cases.length,
  "Duplicate component story",
);
for (const c of fixture.cases) {
  assert(
    inventory.components.some((component) => component.id === c.componentId),
    `Missing design component ${c.componentId}`,
  );
  if (c.reference === "available")
    assert(fixture.boards.some((b) => b.id === c.frameId && b.mode === c.mode));
  else assert(c.reference === "missing" && c.frameId === null && c.nodeId === null);
  assert(c.box.width > 0 && c.box.height > 0);
}
assert.deepEqual(
  [...new Set(fixture.cases.map((c) => c.componentId))].sort(),
  inventory.components.map((c) => c.id).sort(),
  "Every reusable component needs harness stories",
);
for (const component of inventory.components)
  for (const mode of ["light", "dark", "hc-light", "hc-dark"])
    assert(
      fixture.cases.some((c) => c.componentId === component.id && c.mode === mode),
      `Missing ${component.id}/${mode}`,
    );
const content = `// @generated by scripts/component-harness.mjs. TEST DATA from the design's component specimens.

import type { Meta, StoryObj } from "@storybook/react-vite";
import { useEffect, useMemo } from "react";
import { componentCases, createHarnessServices, HarnessSpecimen } from "../src/harness";

function Specimen({ caseId }: { caseId: string }) {
  const services = useMemo(() => createHarnessServices(), []);
  useEffect(() => () => services.dispose(), [services]);
  const specimen = componentCases.find(c => c.id === caseId);
  if (!specimen) throw Error("Missing harness case");
  return <HarnessSpecimen specimen={specimen} services={services} />;
}
const meta = { title: "Harness/Components", component: Specimen } satisfies Meta<typeof Specimen>;
export default meta;
type Story = StoryObj<typeof meta>;
${fixture.cases.map((c, i) => `export const Case${String(i + 1).padStart(3, "0")}: Story = { name: ${JSON.stringify(`${c.name} / ${c.variant} / ${c.mode} (${c.componentId})`)}, args: { caseId: ${JSON.stringify(c.id)} } };`).join("\n")}
`;
const path = root + "packages/editor-react/fixtures/components.stories.tsx";
// The generator owns formatting so --check is byte-for-byte, including after pnpm format.
const { spawnSync } = await import("node:child_process");
const formatted = spawnSync(
  root + "node_modules/.bin/biome",
  ["format", "--stdin-file-path", path],
  { input: content, encoding: "utf8" },
);
assert.equal(formatted.status, 0, formatted.stderr);
if (process.argv.includes("--check"))
  assert.equal(
    readFileSync(path, "utf8"),
    formatted.stdout,
    "Component stories are stale; run harness:generate",
  );
else writeFileSync(path, formatted.stdout);
console.log(
  `Component harness: ${fixture.cases.length} stories; ${fixture.boards.length} boards; design source current`,
);
