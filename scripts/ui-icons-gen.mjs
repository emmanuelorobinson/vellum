#!/usr/bin/env node
// Writes packages/editor-react/src/icons/lucide.generated.ts: the Lucide icons the editor chrome uses, taken from the
// catalog in crates/adapters/icons/data/lucide.json (lucide-static, ISC; see THIRD_PARTY_NOTICES.md). No icon package
// is a dependency. `--check` fails when the committed file differs from what the list would generate.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const catalog = JSON.parse(readFileSync(`${root}crates/adapters/icons/data/lucide.json`, "utf8"));
const list = JSON.parse(
  readFileSync(`${root}packages/editor-react/src/icons/lucide-names.json`, "utf8"),
);
const out = `${root}packages/editor-react/src/icons/lucide.generated.ts`;
const paths = new Map(catalog.icons.map(([name, , d]) => [name, d]));
const names = [...new Set(list.names)].sort();
for (const name of names)
  if (!paths.has(name)) {
    console.error(`ui-icons-gen: ${name} is not in ${catalog.package}`);
    process.exit(1);
  }
for (const [alias, target] of Object.entries(list.aliases))
  if (!names.includes(target)) {
    console.error(`ui-icons-gen: alias ${alias} points at ${target}, which is not listed`);
    process.exit(1);
  }
const body = names
  .map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(paths.get(n))},`)
  .join("\n");
const aliases = Object.entries(list.aliases)
  .map(([a, t]) => `  ${JSON.stringify(a)}: ${JSON.stringify(t)},`)
  .join("\n");
const content = `// @generated by scripts/ui-icons-gen.mjs from ${catalog.package} (${catalog.licence}). Do not edit.
// 24 x 24 stroke icons; the editor draws them at 1.5 px.

export const LUCIDE_PATHS: Readonly<Record<string, string>> = {
${body}
};
/** Names the design uses that the catalog's version spells differently. */
export const LUCIDE_ALIASES: Readonly<Record<string, string>> = {
${aliases}
};
`;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== content) {
    console.error("ui-icons-gen: lucide.generated.ts is out of date; run pnpm ui-icons:gen");
    process.exit(1);
  }
  console.log(`ui-icons-gen: ${names.length} icons current`);
} else {
  writeFileSync(out, content);
  console.log(`ui-icons-gen: wrote ${names.length} icons`);
}
