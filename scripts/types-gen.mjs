#!/usr/bin/env node
// Generates packages/types-ts from crates/vellum-types with ts-rs.
//
//   node scripts/types-gen.mjs                      regenerate packages/types-ts/src
//   node scripts/types-gen.mjs --check [--target d] fail if <d> (default: packages/types-ts/src) differs
//
// The output is GENERATED: never hand-edit it. ts-rs writes one file per type; this script adds index.ts.
import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const target = args.includes("--target")
  ? args[args.indexOf("--target") + 1]
  : join(repo, "packages", "types-ts", "src");

const scratch = mkdtempSync(join(tmpdir(), "vellum-types-gen-"));
try {
  // The environment variable beats .cargo/config.toml, so a check never touches the repo.
  const run = spawnSync("cargo", ["test", "-p", "vellum-types", "--lib", "--quiet"], {
    cwd: repo,
    encoding: "utf8",
    env: { ...process.env, TS_RS_EXPORT_DIR: join(scratch, "generated") },
  });
  if (run.status !== 0) {
    console.error(run.stdout, run.stderr);
    console.error("types:gen failed: cargo test -p vellum-types did not pass");
    process.exit(1);
  }

  const generatedDir = join(scratch, "generated");
  const names = readdirSync(generatedDir)
    .filter((f) => f.endsWith(".ts"))
    .sort();
  if (names.length === 0) {
    console.error("types:gen failed: ts-rs exported no bindings");
    process.exit(1);
  }
  const expected = new Map(
    names.map((n) => [`generated/${n}`, readFileSync(join(generatedDir, n), "utf8")]),
  );
  const index = [
    "// @generated by scripts/types-gen.mjs from crates/vellum-types. DO NOT EDIT: run `pnpm types:gen`.",
    ...names.map(
      (n) =>
        `export type { ${n.replace(/\.ts$/, "")} } from "./generated/${n.replace(/\.ts$/, "")}";`,
    ),
    "",
  ].join("\n");
  expected.set("index.ts", index);

  if (check) {
    const problems = [];
    for (const [rel, content] of expected) {
      const file = join(target, rel);
      if (!existsSync(file)) problems.push(`missing: ${rel}`);
      else if (readFileSync(file, "utf8") !== content)
        problems.push(`differs from generated output: ${rel}`);
    }
    const onDisk = existsSync(join(target, "generated"))
      ? readdirSync(join(target, "generated")).filter((f) => f.endsWith(".ts"))
      : [];
    for (const f of onDisk)
      if (!expected.has(`generated/${f}`))
        problems.push(`stale: generated/${f} is no longer generated`);
    if (problems.length) {
      for (const p of problems) console.error(p);
      console.error("types-ts has drifted from vellum-types. Run: pnpm types:gen");
      process.exit(1);
    }
    console.log(`types-ts matches vellum-types (${names.length} types)`);
  } else {
    rmSync(join(target, "generated"), { recursive: true, force: true });
    mkdirSync(join(target, "generated"), { recursive: true });
    for (const [rel, content] of expected) writeFileSync(join(target, rel), content);
    console.log(`wrote ${names.length} types to ${join("packages", "types-ts", "src")}`);
  }
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
