//! TEST DATA. Pixels and injected local segmentation; no model downloads.
use vellum_core::ports::{ImageOps, SegmentationModel};
use vellum_image_ops::{LocalImageOps, encode_png};
struct Mask;
impl SegmentationModel for Mask {
    fn mask(
        &self,
        _: &[u8],
        w: u32,
        h: u32,
    ) -> Result<Vec<f32>, vellum_core::ports::ImageWorkError> {
        Ok((0..w * h)
            .map(|i| if i % 2 == 0 { 0.0 } else { 1.0 })
            .collect())
    }
}
#[test]
fn segmentation_preserves_source_alpha_and_trace_returns_svg() {
    let png = encode_png(2, 1, &[200, 20, 10, 255, 20, 200, 10, 80]).unwrap();
    let ops = LocalImageOps::new(Some(Box::new(Mask)));
    let out = ops.remove_background(&png).unwrap();
    let decoded = image::load_from_memory(&out.bytes).unwrap().to_rgba8();
    assert_eq!(decoded.get_pixel(0, 0)[3], 0);
    assert_eq!(decoded.get_pixel(1, 0)[3], 80);
    let svg = ops.trace(&png).unwrap();
    assert!(svg.contains("<svg"));
    assert!(ops.trace(b"broken").is_err());
    assert!(LocalImageOps::new(None).remove_background(&png).is_err());
}

#[test]
fn configured_adapter_meets_shared_contract_and_rejects_bad_masks() {
    let png = encode_png(8, 8, &[80, 180, 90, 255].repeat(64)).unwrap();
    vellum_contracts::suites::media::image_ops(&LocalImageOps::new(Some(Box::new(Mask))), &png);
    struct Bad;
    impl SegmentationModel for Bad {
        fn mask(
            &self,
            _: &[u8],
            _: u32,
            _: u32,
        ) -> Result<Vec<f32>, vellum_core::ports::ImageWorkError> {
            Ok(vec![f32::NAN])
        }
    }
    assert!(
        LocalImageOps::new(Some(Box::new(Bad)))
            .remove_background(&png)
            .is_err()
    );
    let mut huge = png.clone();
    huge[16..20].copy_from_slice(&u32::MAX.to_be_bytes());
    assert!(LocalImageOps::new(None).trace(&huge).is_err());
}
#[test]
#[ignore = "native-model lane: needs VELLUM_TEST_ONNX_MODEL, generated by scripts/image-model-fixture.py"]
fn native_onnx_inference() {
    let model = std::env::var_os("VELLUM_TEST_ONNX_MODEL").expect("model path");
    let model = vellum_image_ops::OnnxSegmentation::open(std::path::Path::new(&model)).unwrap();
    let input = [255, 0, 0, 255, 0, 255, 0, 255];
    let mask = model.mask(&input, 2, 1).unwrap();
    assert_eq!(mask.len(), 2);
    assert!(
        mask[0] > 0.8 && mask[1] < 0.2,
        "foreground follows red-channel fixture model"
    );
}

#[test]
fn tracing_artwork_with_transparency_is_deterministic() {
    // Transparent pixels are keyed out with a colour the image does not use; the choice must not vary.
    let mut px = Vec::new();
    for y in 0..16u8 {
        for x in 0..16u8 {
            px.extend(if (4..12).contains(&x) && (4..12).contains(&y) {
                [255, 0, 0, 255]
            } else {
                [0, 0, 0, 0]
            });
        }
    }
    let png = encode_png(16, 16, &px).unwrap();
    let ops = LocalImageOps::new(None);
    let first = ops.trace(&png).unwrap();
    assert!(first.contains("<path"), "{first}");
    for _ in 0..4 {
        assert_eq!(ops.trace(&png).unwrap(), first);
    }
}
