//! One registry supplies dispatch, discovery, mutation classification and declarations.
pub const API_VERSION: &str = "1.0";
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Method {
    Page,
    Get,
    Query,
    Insert,
    Update,
    Copy,
    Replace,
    Move,
    Delete,
    SetVariables,
    CreateComponent,
    MakeSlot,
    Instance,
    FindSpace,
    LayoutProblems,
    Screenshot,
    Export,
    FillImage,
    Icon,
    Claim,
    Release,
}
pub struct Descriptor {
    pub method: Method,
    pub name: &'static str,
    pub signature: &'static str,
    pub mutates: bool,
}
macro_rules! registry { ($($method:ident, $name:literal, $signature:literal, $writes:literal;)*) => {
    pub const REGISTRY: &[Descriptor] = &[$(Descriptor { method: Method::$method, name: $name, signature: $signature, mutates: $writes }),*];
    pub const FUNCTIONS: &[&str] = &[$($name),*];
}; }
registry! {
    Page, "page", "(nameOrId: string): PageId", false;
    Get, "get", "(id: NodeId): Node | null", false;
    Query, "query", "(filter?: { type?: Node['type']; name?: string; scope?: NodeId | PageId }): Node[]", false;
    Insert, "insert", "(parent: NodeId | PageId, node: NodeSpec, index?: number): NodeId", true;
    Update, "update", "(id: NodeId, patch: NodePatch): NodeId", true;
    Copy, "copy", "(id: NodeId, parent: NodeId | PageId, index?: number): NodeId", true;
    Replace, "replace", "(id: NodeId, node: NodeSpec): NodeId", true;
    Move, "move", "(id: NodeId, parent: NodeId | PageId, index?: number): NodeId", true;
    Delete, "delete", "(id: NodeId): null", true;
    SetVariables, "setVariables", "(set: Record<VariableId, Variable>, remove?: VariableId[]): null", true;
    CreateComponent, "createComponent", "(id: NodeId, componentId?: ComponentId): ComponentId", true;
    MakeSlot, "makeSlot", "(id: NodeId, suggested?: ComponentId[]): NodeId", true;
    Instance, "instance", "(parent: NodeId | PageId, component: ComponentId, options?: InstanceOptions): NodeId", true;
    FindSpace, "findSpace", "(page: PageId, size: {width: number; height: number; near?: {x: number; y: number}}): Rect", false;
    LayoutProblems, "layoutProblems", "(id: NodeId | PageId): JsonValue", false;
    Screenshot, "screenshot", "(id: NodeId | PageId, options?: {scale?: number}): JsonValue", false;
    Export, "export", "(id: NodeId | PageId, options: {format: 'png' | 'svg' | 'pdf'}): JsonValue", false;
    FillImage, "fillImage", "(id: NodeId, asset: AssetId): NodeId", true;
    Icon, "icon", "(parent: NodeId | PageId, icon: string, options: IconOptions): NodeId", true;
    Claim, "claim", "(id: NodeId): null", false;
    Release, "release", "(id: NodeId): null", false;
}
/// Uses the generated file-format types, including distributive NodeSpec for every node kind.
pub fn declarations() -> String {
    let mut out = format!(
        "// @generated by scripts/doc-api-gen.mjs. DO NOT EDIT.\nimport type {{ Node, NodeId, PageId, ComponentId, VariableId, Variable, AssetId, NodePatch, Scalar }} from '@vellum/types-ts';\nexport type JsonValue = null | boolean | number | string | JsonValue[] | {{[key: string]: JsonValue}};\nexport type Rect = {{x: number; y: number; width: number; height: number}};\ninterface NodeChildren {{children?: NodeSpec[]}}\ntype Spec<T> = T extends Node ? Omit<T, 'id' | 'name' | 'children'> & {{id?: NodeId; name?: string}} & (T extends {{children?: Node[]}} ? NodeChildren : object) : never;\nexport type NodeSpec = Spec<Node>;\nexport type InstanceOptions = Partial<Omit<Extract<Node, {{type:'instance'}}>, 'id' | 'type' | 'componentId'>>;\nexport type IconOptions = Omit<Extract<Node, {{type:'icon'}}>, 'id' | 'name' | 'type' | 'icon' | 'library' | 'weight'> & {{name?: string; weight?: number}};\nexport interface VellumDoc {{\n  readonly apiVersion: '{API_VERSION}';\n"
    );
    for d in REGISTRY {
        out.push_str(&format!("  {}{};\n", d.name, d.signature));
    }
    out.push_str("}\nexport interface VellumScriptNode<Inputs extends Record<string, Scalar>> {readonly apiVersion: VellumDoc['apiVersion']; readonly inputs: Readonly<Inputs>}\nexport declare const doc: VellumDoc;\n");
    out
}
